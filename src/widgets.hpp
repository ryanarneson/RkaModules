// The endless encoder in the Instrument look: 14.5 mm, knurled, no index
// (it has no end stops). The knurl turns 1/24 turn per detent taken; it has
// 55 ticks, so each detent shifts it 7/24 of a tick and the picture does not
// repeat within a turn.
struct KnurlEncoder : Encoder {
	std::shared_ptr<window::Svg> body[2], knurl[2];

	KnurlEncoder() {
		box.size = mm2px(Vec(14.5f, 14.5f));
		for (int dark = 0; dark < 2; dark++) {
			body[dark] = instrumentArt("Encoder_bg", dark);
			knurl[dark] = instrumentArt("Encoder", dark);
		}
	}

	void draw(const DrawArgs& args) override {
		const int dark = settings::preferDarkPanels ? 1 : 0;
		if (body[dark] && body[dark]->handle)
			window::svgDraw(args.vg, body[dark]->handle);
		if (knurl[dark] && knurl[dark]->handle) {
			const Vec c = box.size.div(2.f);
			nvgSave(args.vg);
			nvgTranslate(args.vg, c.x, c.y);
			nvgRotate(args.vg, float(2.0 * M_PI) * float(((position % 24) + 24) % 24) / 24.f);
			nvgTranslate(args.vg, -c.x, -c.y);
			window::svgDraw(args.vg, knurl[dark]->handle);
			nvgRestore(args.vg);
		}
	}
};

// Draws a 1-bit 128x64 frame (bit y%8 of byte (y/8)*128 + x, the SSD1306
// page layout) scaled to its box, in the self-illuminating layer, lit
// pixels in `colour` as horizontal runs, one path per frame.
struct PixelScreen : widget::Widget {
	static constexpr int W = 128, H = 64, BYTES = W * H / 8;

	std::function<bool(uint8_t* frame)> source;   // fills BYTES; false: draw nothing
	NVGcolor colour = RkaTheme::CYAN;
	uint8_t frame[BYTES] = {};

	bool lit(int x, int y) const {
		return (frame[(y / 8) * W + x] >> (y % 8)) & 1;
	}

	void drawLayer(const DrawArgs& args, int layer) override {
		if (layer == 1 && source && source(frame)) {
			const float px = box.size.x / W, py = box.size.y / H;
			// No anti-aliasing: pixel edges fall between device pixels, and
			// AA would show seams between adjacent rows of lit pixels.
			nvgSave(args.vg);
			nvgShapeAntiAlias(args.vg, false);
			nvgBeginPath(args.vg);
			for (int y = 0; y < H; y++) {
				for (int x = 0; x < W;) {
					if (!lit(x, y)) {
						x++;
						continue;
					}
					int end = x + 1;
					while (end < W && lit(end, y))
						end++;
					nvgRect(args.vg, x * px, y * py, (end - x) * px, py);
					x = end;
				}
			}
			nvgFillColor(args.vg, colour);
			nvgFill(args.vg);
			nvgRestore(args.vg);
		}
		Widget::drawLayer(args, layer);
	}
};

