// The press and release of a momentary button that shift-click latches
// (HoldButton, CapButton). `latching`: the press that started this drag
// latched the button, so it stays down on release.
inline void holdPress(ParamQuantity* pq, bool& latching) {
	if (!pq)
		return;
	// Down at a press means latched (or loaded down): this click releases it.
	if (pq->getValue() > 0.f) {
		latching = false;
		pq->setMin();
		return;
	}
	latching = (APP->window->getMods() & RACK_MOD_MASK) == GLFW_MOD_SHIFT;
	pq->setMax();
}

inline void holdRelease(ParamQuantity* pq, bool& latching) {
	if (pq && !latching)
		pq->setMin();
	latching = false;
}

// A 6 mm momentary button with an amber light. Click: down while held.
// Shift-click: latches down until the next click of either kind (which only
// releases it). The light is on while the param is above 0. Configure the
// param with configButton() so it is not randomised.
struct HoldButton : app::ParamWidget {
	// The press that started this drag latched the button: keep it down on release.
	bool latching = false;

	HoldButton() {
		box.size = mm2px(Vec(6.f, 6.f));
	}

	bool isDown() {
		ParamQuantity* pq = getParamQuantity();
		return pq && pq->getValue() > 0.f;
	}

	void onDragStart(const DragStartEvent& e) override {
		if (e.button == GLFW_MOUSE_BUTTON_LEFT)
			holdPress(getParamQuantity(), latching);
	}

	void onDragEnd(const DragEndEvent& e) override {
		if (e.button == GLFW_MOUSE_BUTTON_LEFT)
			holdRelease(getParamQuantity(), latching);
	}

	// No double-click reset: a button has nothing to reset.
	void onDoubleClick(const DoubleClickEvent& e) override {}

	void draw(const DrawArgs& args) override {
		const Vec c = box.size.div(2.f);
		const float r = box.size.x / 2.f;
		nvgBeginPath(args.vg);
		nvgCircle(args.vg, c.x, c.y, r - 0.5f);
		nvgFillColor(args.vg, RkaTheme::CARD);
		nvgFill(args.vg);
		nvgStrokeColor(args.vg, RkaTheme::HINT);
		nvgStrokeWidth(args.vg, 1.f);
		nvgStroke(args.vg);
		// The unlit lens.
		nvgBeginPath(args.vg);
		nvgCircle(args.vg, c.x, c.y, r * 0.55f);
		nvgFillColor(args.vg, nvgTransRGBAf(RkaTheme::HINT, 0.35f));
		nvgFill(args.vg);
		ParamWidget::draw(args);
	}

	void drawLayer(const DrawArgs& args, int layer) override {
		if (layer == 1 && isDown()) {
			const Vec c = box.size.div(2.f);
			const float r = box.size.x / 2.f;
			nvgBeginPath(args.vg);
			nvgCircle(args.vg, c.x, c.y, r * 0.55f);
			nvgFillColor(args.vg, RkaTheme::AMBER);
			nvgFill(args.vg);
			// Halo.
			nvgBeginPath(args.vg);
			nvgCircle(args.vg, c.x, c.y, r * 1.3f);
			nvgFillPaint(args.vg, nvgRadialGradient(args.vg, c.x, c.y, r * 0.5f, r * 1.3f,
				nvgTransRGBAf(RkaTheme::AMBER, 0.35f), nvgTransRGBAf(RkaTheme::AMBER, 0.f)));
			nvgFill(args.vg);
		}
		ParamWidget::drawLayer(args, layer);
	}
};

// Sets a param the way a click on a stock switch does: Edit > Undo puts it
// back. Nothing is recorded when the value does not change.
inline void setParamUndoable(ParamQuantity* pq, float value, const std::string& action) {
	if (!pq || !pq->module)
		return;
	const float oldValue = pq->getValue();
	pq->setValue(value);
	const float newValue = pq->getValue();
	if (newValue == oldValue)
		return;
	history::ParamChange* h = new history::ParamChange;
	h->name = action;
	h->moduleId = pq->module->id;
	h->paramId = pq->paramId;
	h->oldValue = oldValue;
	h->newValue = newValue;
	APP->history->push(h);
}

// A latch in the HoldButton's shape: each click flips the param between its
// minimum and its maximum, undoably. It lights itself while the param is at
// its maximum: the whole lens cyan, with a halo, on the light layer (full
// brightness in a dimmed room); off, the lens is dark. Configure the param
// with configSwitch().
struct LatchButton : HoldButton {
	// Lit with no module (the module browser): the param's default.
	bool litWithoutModule = false;

	bool lit() {
		ParamQuantity* pq = getParamQuantity();
		return pq ? pq->getValue() > 0.5f * (pq->getMinValue() + pq->getMaxValue()) : litWithoutModule;
	}

	void onDragStart(const DragStartEvent& e) override {
		if (e.button != GLFW_MOUSE_BUTTON_LEFT)
			return;
		ParamQuantity* pq = getParamQuantity();
		if (!pq)
			return;
		setParamUndoable(pq, isDown() ? pq->getMinValue() : pq->getMaxValue(), "move switch");
	}

	void onDragEnd(const DragEndEvent& e) override {}

	void drawLayer(const DrawArgs& args, int layer) override {
		if (layer == 1 && lit()) {
			const Vec c = box.size.div(2.f);
			const float r = box.size.x / 2.f;
			nvgBeginPath(args.vg);
			nvgCircle(args.vg, c.x, c.y, r * 0.7f);
			nvgFillColor(args.vg, RkaTheme::CYAN);
			nvgFill(args.vg);
			nvgBeginPath(args.vg);
			nvgCircle(args.vg, c.x, c.y, r * 1.45f);
			nvgFillPaint(args.vg, nvgRadialGradient(args.vg, c.x, c.y, r * 0.6f, r * 1.45f,
				nvgTransRGBAf(RkaTheme::CYAN, 0.4f), nvgTransRGBAf(RkaTheme::CYAN, 0.f)));
			nvgFill(args.vg);
		}
		ParamWidget::drawLayer(args, layer);
	}
};

// An endless 13.4 mm encoder; not a Rack param, so nothing is saved or
// randomised. Vertical drag: one detent per 8 px of mouse travel, upward is
// clockwise (Ctrl/Cmd: 32 px). Scroll wheel over it: one detent per notch,
// only when Rack's "scroll wheel knob control" setting is on (as Rack's
// knobs); otherwise the rack scrolls. The pointer turns 1/24 turn per detent
// that onTurn takes; detents it refuses are kept and offered again.
struct Encoder : widget::OpaqueWidget {
	// > 0 clockwise. Returns false if the turn was not taken: the pointer
	// stays and the detents are offered again (TurnBacklog).
	std::function<bool(int detents)> onTurn;

	int position = 0;   // detents taken since creation, for the pointer
	DetentCounter drag, scroll;
	TurnBacklog backlog;

	Encoder() {
		box.size = mm2px(Vec(13.4f, 13.4f));
	}

	// A turn onTurn refuses waits in the backlog, added to by later turns,
	// and is offered again with them and every frame (step) until taken.
	void turn(int detents) {
		backlog.add(detents);
		offer();
	}

	void offer() {
		const int n = backlog.unsent;
		if (n != 0 && onTurn && onTurn(n)) {
			position += n;
			backlog.clear();
		}
	}

	void step() override {
		offer();
		OpaqueWidget::step();
	}

	void onDragStart(const DragStartEvent& e) override {
		if (e.button != GLFW_MOUSE_BUTTON_LEFT)
			return;
		drag.clear();
		if (settings::allowCursorLock)
			APP->window->cursorLock();
	}

	void onDragMove(const DragMoveEvent& e) override {
		if (e.button != GLFW_MOUSE_BUTTON_LEFT)
			return;
		const bool fine = (APP->window->getMods() & RACK_MOD_MASK) == RACK_MOD_CTRL;
		turn(drag.add(-e.mouseDelta.y, fine ? FINE_DRAG_PX_PER_DETENT : DRAG_PX_PER_DETENT));
	}

	void onDragEnd(const DragEndEvent& e) override {
		if (e.button != GLFW_MOUSE_BUTTON_LEFT)
			return;
		if (settings::allowCursorLock)
			APP->window->cursorUnlock();
	}

	void onHoverScroll(const HoverScrollEvent& e) override {
		if (!settings::knobScroll)
			return;   // not consumed: the rack scrolls
#if defined ARCH_MAC
		const float notch = scrollUnitsPerNotch(true);
#else
		const float notch = scrollUnitsPerNotch(false);
#endif
		turn(scroll.add(e.scrollDelta.y, notch));
		e.consume(this);
	}

	void onLeave(const LeaveEvent& e) override {
		scroll.clear();
		OpaqueWidget::onLeave(e);
	}

	void draw(const DrawArgs& args) override {
		const Vec c = box.size.div(2.f);
		const float r = box.size.x / 2.f - 0.5f;
		nvgBeginPath(args.vg);
		nvgCircle(args.vg, c.x, c.y, r);
		nvgFillColor(args.vg, RkaTheme::CARD);
		nvgFill(args.vg);
		nvgStrokeColor(args.vg, RkaTheme::HINT);
		nvgStrokeWidth(args.vg, 1.f);
		nvgStroke(args.vg);
		// An inner ring, so it reads as a knob cap rather than a hole.
		nvgBeginPath(args.vg);
		nvgCircle(args.vg, c.x, c.y, r * 0.72f);
		nvgStrokeColor(args.vg, nvgTransRGBAf(RkaTheme::HINT, 0.6f));
		nvgStrokeWidth(args.vg, 0.75f);
		nvgStroke(args.vg);
		const float a = float(2.0 * M_PI) * float(((position % 24) + 24) % 24) / 24.f;
		const Vec dir(std::sin(a), -std::cos(a));
		nvgBeginPath(args.vg);
		nvgMoveTo(args.vg, c.x + dir.x * r * 0.3f, c.y + dir.y * r * 0.3f);
		nvgLineTo(args.vg, c.x + dir.x * (r - 2.f), c.y + dir.y * (r - 2.f));
		nvgStrokeColor(args.vg, RkaTheme::INK);
		nvgStrokeWidth(args.vg, 1.75f);
		nvgLineCap(args.vg, NVG_ROUND);
		nvgStroke(args.vg);
	}
};

