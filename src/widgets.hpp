// Latching button: each click flips the param between its minimum and its
// maximum, undoably. Configure the param with configSwitch().
//
// What lights the cap:
// - made with createParamCentered: the param itself, lit above the middle
//   of its range (Shoal's UI MODE);
// - made with createLightParamCentered(pos, module, paramId, lightId): that
//   light's brightness, so the module decides (Sway's 1-SHOT).
struct CapLatch : Cap {
	// The module light that lights the cap, if any; filled in by
	// createLightParam().
	struct LightRef {
		engine::Module* module = NULL;
		int firstLightId = -1;
	};
	LightRef light;
	// Lit with no module (the module browser), when the param lights the cap.
	bool litWithoutModule = false;

	LightRef* getLight() {
		return &light;
	}

	float lit() override {
		if (light.firstLightId >= 0)
			return light.module ? light.module->lights[light.firstLightId].getBrightness() : 0.f;
		ParamQuantity* pq = getParamQuantity();
		if (!pq)
			return litWithoutModule ? 1.f : 0.f;
		return pq->getValue() > 0.5f * (pq->getMinValue() + pq->getMaxValue()) ? 1.f : 0.f;
	}

	void onDragStart(const DragStartEvent& e) override {
		if (e.button != GLFW_MOUSE_BUTTON_LEFT)
			return;
		ParamQuantity* pq = getParamQuantity();
		if (!pq)
			return;
		const bool up = pq->getValue() > 0.5f * (pq->getMinValue() + pq->getMaxValue());
		setParamUndoable(pq, up ? pq->getMinValue() : pq->getMaxValue(), "move switch");
	}
};

