	std::shared_ptr<window::Svg> body[2];
	std::shared_ptr<window::Svg> glow;

	Cap() {
		box.size = mm2px(Vec(6.4f, 6.4f));
		body[0] = instrumentArt("Cap", false);
		body[1] = instrumentArt("Cap", true);
		glow = instrumentArt("Cap_lit", false);
	}

