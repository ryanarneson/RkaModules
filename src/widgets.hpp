// A component's artwork: res/components/<name>.svg or <name>-dark.svg.
inline std::shared_ptr<window::Svg> instrumentArt(const std::string& name, bool dark) {
	return Svg::load(asset::plugin(pluginInstance, "res/components/" + name + (dark ? "-dark" : "") + ".svg"));
}

// A colour of the Instrument palette for the panel variant on show:
// instrumentColour(RkaTheme::BRASS, RkaTheme::BRASS_DARK).
inline NVGcolor instrumentColour(NVGcolor normal, NVGcolor dark) {
	return settings::preferDarkPanels ? dark : normal;
}

// A knurled knob in two layers: <art>_bg.svg (the body) stays still;
// <art>.svg (knurl, index, centre dot) turns with the param. Its scale and
// bezel are on the panel (a dial face or the limb) and so never turn. 270
// degrees end to end, as the panels' dial faces are graduated.
struct KnurledKnob : app::SvgKnob {
	widget::SvgWidget* bg;
	std::string art;
	int shown = -1;   // 0: normal artwork, 1: dark; -1: none yet

	KnurledKnob() {
		minAngle = -0.75f * float(M_PI);
		maxAngle = 0.75f * float(M_PI);
		shadow->opacity = 0.f;
		bg = new widget::SvgWidget;
		fb->addChildBelow(bg, tw);
	}

	void setArt(const std::string& name) {
		art = name;
		showTheme();
	}

	void showTheme() {
		const int dark = settings::preferDarkPanels ? 1 : 0;
		if (dark == shown || art.empty())
			return;
		shown = dark;
		setSvg(instrumentArt(art, dark));
		bg->setSvg(instrumentArt(art + "_bg", dark));
		fb->setDirty();
	}

	void step() override {
		showTheme();
		SvgKnob::step();
	}
};

